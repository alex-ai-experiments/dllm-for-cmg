#!/usr/bin/env python3
"""
Analyze task diffs to find optimal summary configuration.
==========================================================

This script:
  1. Reads a tasks JSONL file (built by build_tasks.py)
  2. Tokenizes all per-file diffs using the target model's tokenizer
  3. Computes token length distributions and clustering statistics
  4. Recommends optimal diff_cap and batch_size settings that minimize
     padding waste while retaining maximum information

Methodology:
  - Padding waste = extra tokens generated by padding short prompts to
    match the longest prompt in a batch. Minimizing this is critical
    for dLLM efficiency (each padded position is still processed).
  - We simulate different (diff_cap, batch_size) combinations and
    estimate total padding waste + information loss (truncation).
  - The "optimal" config minimizes: α * padding_waste + β * truncation_loss
    where α=1.0, β=2.0 (penalize information loss more than waste).

Usage:
    python main_experiment/105_find_optimal_summary_config.py \\
        --tasks build_tasks/tasks_5k.jsonl

    # Or with a specific tokenizer
    python main_experiment/105_find_optimal_summary_config.py \\
        --tasks build_tasks/tasks_5k.jsonl \\
        --tokenizer Efficient-Large-Model/Fast_dLLM_v2_7B
"""

import argparse
import json
import sys
import math
from pathlib import Path
from collections import defaultdict
from dataclasses import dataclass

# ─── Path setup ───────────────────────────────────────────────────────────────

_SCRIPT_DIR = Path(__file__).resolve().parent
_PROJECT_ROOT = _SCRIPT_DIR.parent
sys.path.insert(0, str(_PROJECT_ROOT / "lib"))

from diff_utils import get_per_file_diffs, build_summary_messages


@dataclass
class FileInfo:
    """Info about a single file diff within a task."""
    task_id: str
    filename: str
    diff_chars: int
    prompt_tokens: int  # full prompt token length (with chat template)
    diff_tokens: int    # just the diff portion in tokens


@dataclass
class ConfigScore:
    """Score for a (diff_cap, batch_size) configuration."""
    diff_cap: str
    batch_size: int
    total_padding_tokens: int
    total_truncated_chars: int
    truncated_files: int
    total_files: int
    avg_padding_per_batch: float
    padding_waste_pct: float
    truncation_pct: float
    composite_score: float  # lower is better


def percentile(sorted_vals: list[int | float], pct: float) -> float:
    """Interpolated percentile from sorted values."""
    if not sorted_vals:
        return 0.0
    n = len(sorted_vals)
    idx = pct / 100.0 * (n - 1)
    lo = int(idx)
    hi = min(lo + 1, n - 1)
    frac = idx - lo
    return sorted_vals[lo] + frac * (sorted_vals[hi] - sorted_vals[lo])


def analyze_tasks(tasks: list[dict], tokenizer) -> list[FileInfo]:
    """Extract FileInfo for every per-file diff across all tasks."""
    file_infos = []
    for task in tasks:
        task_id = task.get("task_id", "unknown")
        file_diffs = get_per_file_diffs(task)
        for fn, fd in file_diffs:
            diff_chars = len(fd)
            diff_tokens = len(tokenizer(fd, return_tensors="pt")["input_ids"][0])
            msgs = build_summary_messages(fn, fd)
            prompt_text = tokenizer.apply_chat_template(
                msgs, tokenize=False, add_generation_prompt=True
            )
            prompt_tokens = len(
                tokenizer([prompt_text], return_tensors="pt")["input_ids"][0]
            )
            file_infos.append(FileInfo(
                task_id=task_id,
                filename=fn,
                diff_chars=diff_chars,
                prompt_tokens=prompt_tokens,
                diff_tokens=diff_tokens,
            ))
    return file_infos


def estimate_overhead_tokens(file_infos: list[FileInfo]) -> int:
    """Estimate fixed overhead tokens (system prompt + template, excluding diff)."""
    if not file_infos:
        return 0
    # The shortest file has the least diff content → most of its prompt is overhead
    shortest = min(file_infos, key=lambda f: f.diff_tokens)
    return max(0, shortest.prompt_tokens - shortest.diff_tokens)


def simulate_config(
    file_infos: list[FileInfo],
    diff_cap_chars: int | None,
    batch_size: int,
    overhead_tokens: int,
    tokenizer,
    sort_by_length: bool = True,
) -> ConfigScore:
    """Simulate a (diff_cap, batch_size) config and compute waste/truncation."""

    # Step 1: Apply diff_cap and compute effective prompt lengths
    effective_lengths = []
    total_truncated_chars = 0
    truncated_files = 0

    for fi in file_infos:
        if diff_cap_chars is not None and fi.diff_chars > diff_cap_chars:
            # Truncation: estimate effective tokens after char-cap
            ratio = diff_cap_chars / fi.diff_chars
            eff_diff_tokens = max(1, int(fi.diff_tokens * ratio))
            eff_prompt = overhead_tokens + eff_diff_tokens
            total_truncated_chars += fi.diff_chars - diff_cap_chars
            truncated_files += 1
        else:
            eff_prompt = fi.prompt_tokens
        effective_lengths.append(eff_prompt)

    # Step 2: Sort by length if enabled (reduces padding)
    if sort_by_length:
        effective_lengths.sort()

    # Step 3: Simulate batching and compute padding waste
    total_padding = 0
    total_useful = 0
    n_batches = 0

    for i in range(0, len(effective_lengths), batch_size):
        batch = effective_lengths[i:i + batch_size]
        max_in_batch = max(batch)
        for length in batch:
            total_padding += max_in_batch - length
            total_useful += length
        n_batches += 1

    total_tokens = total_useful + total_padding
    padding_waste_pct = (total_padding / max(total_tokens, 1)) * 100
    avg_padding = total_padding / max(n_batches, 1)
    truncation_pct = (truncated_files / max(len(file_infos), 1)) * 100

    # Composite score: weighted sum (lower is better)
    # Padding waste in thousands + truncation penalty
    alpha = 1.0   # padding waste weight
    beta = 2.0    # truncation penalty (information loss is worse)
    composite = alpha * (total_padding / 1000) + beta * (total_truncated_chars / 10000)

    cap_label = f"{diff_cap_chars} chars" if diff_cap_chars is not None else "none"

    return ConfigScore(
        diff_cap=cap_label,
        batch_size=batch_size,
        total_padding_tokens=total_padding,
        total_truncated_chars=total_truncated_chars,
        truncated_files=truncated_files,
        total_files=len(file_infos),
        avg_padding_per_batch=avg_padding,
        padding_waste_pct=padding_waste_pct,
        truncation_pct=truncation_pct,
        composite_score=composite,
    )


def print_distribution(file_infos: list[FileInfo]):
    """Print summary statistics of the file diff distribution."""
    if not file_infos:
        print("No file diffs found.")
        return

    char_lens = sorted([f.diff_chars for f in file_infos])
    tok_lens = sorted([f.diff_tokens for f in file_infos])
    prompt_lens = sorted([f.prompt_tokens for f in file_infos])

    # Tasks stats
    tasks = defaultdict(int)
    for f in file_infos:
        tasks[f.task_id] += 1
    files_per_task = sorted(tasks.values())

    print()
    print("=" * 70)
    print("  TASK & FILE DIFF DISTRIBUTION")
    print("=" * 70)
    print(f"  Total tasks         : {len(tasks)}")
    print(f"  Total file diffs    : {len(file_infos)}")
    print(f"  Files per task      : min={min(files_per_task)}  "
          f"median={percentile(files_per_task, 50):.0f}  "
          f"max={max(files_per_task)}  "
          f"mean={sum(files_per_task)/len(files_per_task):.1f}")
    print()
    print("  Diff length (chars):")
    print(f"    min={min(char_lens):>7}   p25={percentile(char_lens, 25):>7.0f}   "
          f"p50={percentile(char_lens, 50):>7.0f}   p75={percentile(char_lens, 75):>7.0f}   "
          f"p90={percentile(char_lens, 90):>7.0f}   p95={percentile(char_lens, 95):>7.0f}   "
          f"max={max(char_lens):>7}")
    print()
    print("  Diff length (tokens):")
    print(f"    min={min(tok_lens):>7}   p25={percentile(tok_lens, 25):>7.0f}   "
          f"p50={percentile(tok_lens, 50):>7.0f}   p75={percentile(tok_lens, 75):>7.0f}   "
          f"p90={percentile(tok_lens, 90):>7.0f}   p95={percentile(tok_lens, 95):>7.0f}   "
          f"max={max(tok_lens):>7}")
    print()
    print("  Full prompt length (tokens, incl. chat template):")
    print(f"    min={min(prompt_lens):>7}   p25={percentile(prompt_lens, 25):>7.0f}   "
          f"p50={percentile(prompt_lens, 50):>7.0f}   p75={percentile(prompt_lens, 75):>7.0f}   "
          f"p90={percentile(prompt_lens, 90):>7.0f}   p95={percentile(prompt_lens, 95):>7.0f}   "
          f"max={max(prompt_lens):>7}")
    print("=" * 70)


def find_optimal_config(
    file_infos: list[FileInfo],
    overhead_tokens: int,
    tokenizer,
) -> list[ConfigScore]:
    """Grid search over diff_cap × batch_size and rank by composite score."""

    # Compute percentile-based char caps from the data
    char_lens = sorted([f.diff_chars for f in file_infos])
    p50_chars = int(percentile(char_lens, 50))
    p75_chars = int(percentile(char_lens, 75))
    p90_chars = int(percentile(char_lens, 90))

    diff_caps = [
        None,           # no cap
        p90_chars,      # p90
        p75_chars,      # p75
        p50_chars,      # p50
        1500,           # fixed common values
        1000,
        800,
        600,
        400,
    ]
    # Deduplicate and sort
    diff_caps = sorted(set(c for c in diff_caps if c is not None), reverse=True)
    diff_caps = [None] + diff_caps  # None (no cap) first

    batch_sizes = [1, 2, 4, 8]

    scores = []
    for cap in diff_caps:
        for bs in batch_sizes:
            score = simulate_config(
                file_infos, cap, bs, overhead_tokens, tokenizer,
                sort_by_length=True,
            )
            scores.append(score)

    scores.sort(key=lambda s: s.composite_score)
    return scores


def print_results_table(scores: list[ConfigScore], top_n: int = 20):
    """Print a ranked table of configurations."""
    print()
    print("=" * 105)
    print("  CONFIGURATION RANKING (lower composite score = better)")
    print("  Composite = 1.0 * padding_waste/1k + 2.0 * truncation_chars/10k")
    print("=" * 105)
    header = (
        f"{'Rank':>4}  {'diff_cap':>12}  {'batch':>5}  "
        f"{'pad_waste%':>10}  {'trunc%':>7}  {'trunc_files':>11}  "
        f"{'pad_tokens':>10}  {'trunc_chars':>11}  {'score':>8}"
    )
    print(header)
    print("-" * 105)

    for i, s in enumerate(scores[:top_n], 1):
        print(
            f"{i:>4}  {s.diff_cap:>12}  {s.batch_size:>5}  "
            f"{s.padding_waste_pct:>9.1f}%  {s.truncation_pct:>6.1f}%  "
            f"{s.truncated_files:>6}/{s.total_files:<4}  "
            f"{s.total_padding_tokens:>10,}  {s.total_truncated_chars:>11,}  "
            f"{s.composite_score:>8.1f}"
        )

    print("=" * 105)


def print_recommendation(scores: list[ConfigScore], file_infos: list[FileInfo]):
    """Print the recommended config with rationale."""
    if not scores:
        return

    best = scores[0]

    # Also find the best with batch_size=4 (sweet spot for T4)
    best_bs4 = next((s for s in scores if s.batch_size == 4), scores[0])

    print()
    print("═" * 70)
    print("  RECOMMENDATION")
    print("═" * 70)
    print(f"  Overall best:")
    print(f"    diff_cap    = {best.diff_cap}")
    print(f"    batch_size  = {best.batch_size}")
    print(f"    padding waste = {best.padding_waste_pct:.1f}%")
    print(f"    truncation    = {best.truncation_pct:.1f}% of files")
    print(f"    score         = {best.composite_score:.1f}")
    print()

    if best_bs4 != best:
        print(f"  Best with batch_size=4 (recommended for T4 VRAM):")
        print(f"    diff_cap    = {best_bs4.diff_cap}")
        print(f"    batch_size  = {best_bs4.batch_size}")
        print(f"    padding waste = {best_bs4.padding_waste_pct:.1f}%")
        print(f"    truncation    = {best_bs4.truncation_pct:.1f}% of files")
        print(f"    score         = {best_bs4.composite_score:.1f}")
        print()

    # Generate config snippet
    cap_val = best_bs4.diff_cap if best_bs4.diff_cap != "none" else "none"
    # Extract numeric cap value
    if "chars" in cap_val:
        cap_val = cap_val.split()[0]

    print("  Suggested config.json 'summary' section:")
    print(f'    "summary": {{')
    print(f'      "max_new_tokens": 128,')
    print(f'      "batch_size": {best_bs4.batch_size},')
    print(f'      "diff_cap": "{cap_val}",')
    print(f'      "sort_by_length": true')
    print(f'    }}')
    print("═" * 70)
    print()


def main():
    parser = argparse.ArgumentParser(
        description="Find optimal summary config by analyzing task diff distributions",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--tasks", required=True,
        help="Path to tasks JSONL file (built by build_tasks.py)",
    )
    parser.add_argument(
        "--tokenizer", default="Qwen/Qwen2.5-1.5B-Instruct",
        help="Tokenizer to use for token length analysis",
    )
    parser.add_argument(
        "--sample", type=int, default=None,
        help="Analyze only the first N tasks (for speed)",
    )
    parser.add_argument(
        "--output", default=None,
        help="Save analysis results to JSON file",
    )
    args = parser.parse_args()

    # Load tasks
    tasks = []
    with open(args.tasks, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                tasks.append(json.loads(line))
    if args.sample:
        tasks = tasks[:args.sample]
    print(f"Loaded {len(tasks)} tasks from {args.tasks}")

    # Load tokenizer
    print(f"Loading tokenizer: {args.tokenizer} ...")
    from transformers import AutoTokenizer
    tokenizer = AutoTokenizer.from_pretrained(args.tokenizer, trust_remote_code=True)

    # Analyze
    print("Analyzing per-file diffs (this may take a minute) ...")
    file_infos = analyze_tasks(tasks, tokenizer)
    print(f"Found {len(file_infos)} file diffs across {len(tasks)} tasks")

    if not file_infos:
        print("No file diffs found. Check your tasks file.")
        return

    # Print distribution
    print_distribution(file_infos)

    # Estimate overhead
    overhead = estimate_overhead_tokens(file_infos)
    print(f"\nEstimated fixed overhead per prompt: ~{overhead} tokens")

    # Find optimal config
    print("\nRunning grid search over (diff_cap × batch_size) ...")
    scores = find_optimal_config(file_infos, overhead, tokenizer)

    # Print results
    print_results_table(scores, top_n=20)
    print_recommendation(scores, file_infos)

    # Save if requested
    if args.output:
        out = {
            "n_tasks": len(tasks),
            "n_files": len(file_infos),
            "overhead_tokens": overhead,
            "distribution": {
                "diff_chars": {
                    "min": min(f.diff_chars for f in file_infos),
                    "p25": percentile(sorted([f.diff_chars for f in file_infos]), 25),
                    "p50": percentile(sorted([f.diff_chars for f in file_infos]), 50),
                    "p75": percentile(sorted([f.diff_chars for f in file_infos]), 75),
                    "p90": percentile(sorted([f.diff_chars for f in file_infos]), 90),
                    "p95": percentile(sorted([f.diff_chars for f in file_infos]), 95),
                    "max": max(f.diff_chars for f in file_infos),
                },
                "diff_tokens": {
                    "min": min(f.diff_tokens for f in file_infos),
                    "p50": percentile(sorted([f.diff_tokens for f in file_infos]), 50),
                    "p75": percentile(sorted([f.diff_tokens for f in file_infos]), 75),
                    "p90": percentile(sorted([f.diff_tokens for f in file_infos]), 90),
                    "max": max(f.diff_tokens for f in file_infos),
                },
            },
            "rankings": [
                {
                    "rank": i + 1,
                    "diff_cap": s.diff_cap,
                    "batch_size": s.batch_size,
                    "padding_waste_pct": round(s.padding_waste_pct, 2),
                    "truncation_pct": round(s.truncation_pct, 2),
                    "composite_score": round(s.composite_score, 2),
                }
                for i, s in enumerate(scores[:30])
            ],
        }
        with open(args.output, "w", encoding="utf-8") as f:
            json.dump(out, f, indent=2)
        print(f"Analysis saved to {args.output}")


if __name__ == "__main__":
    main()
